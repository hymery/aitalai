class TextLines(HTMLParser):
    def __init__(self):
        super().__init__()
        self.parts: list[str] = []

    def handle_data(self, data):
        self.parts.append(data)

    def lines(self):
        return [part.strip() for part in "".join(self.parts).splitlines() if part.strip()]


def state_schools(raw: bytes):
    parser = TextLines()
    parser.feed(raw.decode("cp1251", errors="replace"))
    rows = []
    for line in parser.lines():
        match = re.match(r"^(\d+)\.\s+(Государственное.+)", line)
        if not match or not match.group(2).endswith("."):
            continue
        number, name = int(match.group(1)), match.group(2).rstrip(".")
        rest = name.removeprefix("Государственное бюджетное общеобразовательное учреждение ")
        prefix = rest.split(" ", 1)[0]
        city = CITY_BY_PREFIX.get(prefix, "")
        district = "" if city else DISTRICT_BY_PREFIX.get(prefix, "")
        short = re.sub(r"\s+(?:для|обучающихся)\b.*$", "", rest).replace("N ", "№ ")
        rows.append({
            "id": f"rb-state-{number:03d}", "name": name,
            "short_name": f"ГБОУ {short}", "city": city, "district": district,
            "type": "Государственная школа-интернат" if "интернат" in rest else "Государственная школа",
        })
    return rows


